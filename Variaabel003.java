public class Variaabel003 {
    public static void main(String[] args) {
     int nim1;
     int nim2;
     String nama1;
     String nama2;
     
     //isi variabel
     nim1 = 123;
     nim2 = 234;
     nama1 = "adi";
     nama2 = "budi";

     //cetak variabel
     System.out.println("==============");
     System.out.println("NIM   |   NAMA");
     System.out.println("==============");
     System.out.println(nim1 + "   |   " + nama1);
     System.out.println(nim2 + "   |   " + nama2);
     System.out.println("===============");
    }
}
